            Помимо обычных типов, .Net и C# предлагают возможность создавать обобщённые (или generic) типы и обобщённые методы.

                Обобщённый тип — это тип, который имеет параметр, в качестве которого может выступать другой тип данных. Такой параметр также называется универсальным параметром.

                class Generic<T>
                {
	             public int Field;
                }

            Используя обобщения, вы можете использовать параметр T как тип, с которым будут работать ваши поля, свойства и методы внутри класса, например:

class Generic<T>
{
	public T Field; // Поле типа T

	public void Method(T param) // Параметр типа T
	{

	}
}

            В качестве примера для работы с обобщениями в данном юните возьмём модель классов автомобиля — электрического и бензинового. Поэтому 
            рекомендуем выполнять самостоятельные задания и не удалять код после их выполнения, поскольку вам придётся его модифицировать.

