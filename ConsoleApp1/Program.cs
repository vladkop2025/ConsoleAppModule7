            --------------------------------------
            Работа обобщений
            --------------------------------------

            Когда вы используете обобщение с параметром, например, Generic<int> — в рамках языка и .Net этот тип действует как самостоятельный тип. 
            Т.е. при обращении к нему впервые .Net создаёт тип Generic<int> как отдельный тип, со своими параметрами и типами полей.

            Если же в следующей строке вы создадите переменную типа Generic<long> — среда не будет обращаться к Generic<int>, чтобы заменить какие-то 
            типы на <long>, она точно так же создаст тип Generic<long>.

            Благодаря этому избегается проблема упаковки-распаковки. А также это позволяет обобщениям содержать статические поля, свойства и методы, 
            поскольку в памяти они будут представлены разными типами

            --------------------------------------
            Значение по умолчанию
            --------------------------------------

            У вас может возникнуть необходимость присвоить переменным универсальных параметров некоторое начальное значение, в том числе и null. Но напрямую мы его присвоить не можем:

                class Generic<T>
                {
	                public T Field = null; // Поле типа T
                }

            Такой код вызовет ошибку при компиляции, поскольку значимые типы не могут принимать null, а тип T может быть значимым, в том числе:

            Для того, чтобы разрешить эту проблему в C#, есть такой механизм как значение по умолчанию. Данное значение реализуется с помощью ключевого слова default.

            Для получения значения для определённого типа T стоит вызывать default(T). Данная конструкция вернёт null, если тип T — ссылочный, и 0 — если тип значимый.

            Корректный код будет выглядеть следующим образом:


                class Generic<T>
                {
	                public T Field = default(T); // Поле типа T
                }

