            --------------------------------------
            Перегрузка методов
            --------------------------------------

            Мы подходим к ещё одному инструменту полиморфизма — перегрузке. Но перед этим стоит немного поговорить о сигнатуре метода.

            Вы уже много раз встречались с объявлением методов и даже сами их объявляли. Каждое объявление метода соответствует следующему шаблону:

                [модификатор доступа] [static] <тип возвращаемого значения> <название метода>(
                [<тип параметра 1> <название параметра 1>,
                 <тип параметра 2> <название параметра 2>, ...]
                )

            Где в квадратных скобках — необязательные атрибуты метода, а в угловых скобках — обязательные.

            Компилятор отличает методы по их сигнатуре, а именно, по совокупности следующих аспектов:

                имя метода;
                количество параметров;
                типы параметров;
                порядок параметров;
                модификаторы параметров.

            Сигнатура метода — это уникальный набор информации о методе, состоящий из его имени, количества, типа и порядка параметров а также из модификаторов параметров.

            Например, рассмотрим метод:

                void Greetings(string name) 
                {
                 Console.WriteLine("Привет, {0}", name);
                }

            Данная функция имеет название Greetings и принимает один аргумент типа string. Значит, сигнатура данного метода для компилятора будет выглядеть как:

                Greetings(string)


            Поскольку сигнатура не включает в себя тип возвращаемого значения и наименования аргументов, данные методы будут иметь одинаковую сигнатуру Greetings(string, string):

void Greetings(string name, string surname) 
{
  Console.WriteLine($ "Рад снова Вас видеть, {surname} {name}");
}

string Greetings(string name, string surname) 
{
  return $ "Приветствую, {surname} {name}";
}

string Greetings(string firstUser, string secondUser) 
{
  return $ "Добро пожаловать, {firstUser} и {secondUser}";
}

            Представьте, что вам нужно создать метод для нахождения суммы 2 целочисленных переменных. Ваше решение будет похоже на это:

int Sum(int a, int b) 
{
  return a + b;
}

            Данный метод работает с 2 переменными типа int и полностью удовлетворяет требованиям. Но далее у вас возникает запрос на создание 
            такого метода для переменных типа long, double и даже для сложения 3 переменных типа int.

            При чем здесь перегрузка?

            Можно создавать новые методы с названиями вроде SumLong, SumDouble, SumIntThreeVar или Sum1, Sum2, Sum3. Но такое объявление методов 
            лишь сделает код менее читаемым и более запутанным.

            А можно воспользоваться перегрузкой.

                        Перегрузка метода — это возможность использования разных методов с одинаковым названием, но отличными друг от друга сигнатурами.

            Благодаря возможности перегрузки мы можем решить данную задачу с методом Sum следующим образом:

long Sum(long a, long b) 
{
  return a + b;
}

double Sum(double a, double b) 
{
  return a + b;
}

int Sum(int a, int b, int c) 
{
  return a + b + c;
}

            Используя перегрузку, вы сохраняете чистоту кода. А поскольку у всех перегруженных методов разные сигнатуры, компилятор определяет 
            их как разные методы и без труда может определить, какой метод вы используете.

            Также IntelliSense в Visual Studio помогает определить, какие у метода есть перегрузки и как вы можете его использовать. При появлении
            выпадающей подсказки о методе, вы можете переключать перегрузки метода стрелочками «Вверх» и «Вниз».

