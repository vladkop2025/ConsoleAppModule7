            --------------------------------------
            Наследование обобщений
            --------------------------------------

            Обобщённые классы могут наследоваться друг от друга так же, как и обычный класс может наследоваться от обобщённого. Существует два основных типа такого наследования:

                Наследование от обобщения без указания его типа. В данном методе наследование происходит от «базового» обобщения, в котором параметр не указан. 
                Таким образом, наследник типизирован тем же типом, что и базовый. Такой тип «пробрасывается» между ними.

                Наследование от обобщения с указанием его типа. Для этого базовому типу указывается конкретное значение универсального параметра, и уже от него происходит 
                наследование. Лучше всего пояснить данный процесс на примерах.

            Возьмём следующий базовый класс:

            class BaseClass<T>
            {
	            public T Field;
            }

            И унаследуемся от обобщения без указания типа, т.е. от класса BaseClass<T>. Поскольку T не является настоящим типом, нам придётся добавлять универсальный 
            параметр в класс-наследник, таким образом создавая новое обобщение:

                class DerivedClass<T> : BaseClass<T>
                {
	                public T Property { get; set; }
                }

            Мы реализовали наследование без указания типа. Важно понимать, что с таким способом наследования класс-наследник может быть только обобщённым. Но это повышает гибкость.

            Использование такого класса выглядит следующим образом: (см. код ниже)

                    DerivedClass<int> derived = new DerivedClass<int>();
                    derived.Field = 13; // Тип int
                    derived.Property = 22;	// Тип int

            Следующий способ — с указанием типа. Для этого вместо T подставим определённый тип, например, int. Таким образом, мы будем наследоваться от класса BaseClass<int>:

                class DerivedClass : BaseClass<int>
                {
	                public string Property { get; set; }
                }

            В данном случае классу-наследнику необязательно быть обобщением, это может быть и обычный класс. Его использование будет выглядеть как:

                class BaseClass<T> 
                {
                     public T Field;
        
                }
              
                class DerivedClass<T> : BaseClass<int>  // поле Field всегда будет иметь тип int
                {
                    public T Property { set; get; }

                 }

                DerivedClass derived = new DerivedClass();
                derived.Field = 13;		// Тип int
                derived.Property = "22";	// Тип string

            Также можно создавать класс-наследник как обобщение, у которого будет свой собственный тип:

                class DerivedClass<T> : BaseClass<int>
                {
	                public T Property { get; set; }
                }

                DerivedClass<string> derived = new DerivedClass<string>();
                derived.Field = 13;		// Всегда тип int
                derived.Property = "22";	// Тип string 0 принимает тип передаваемого значения

            При этом стоит учитывать, что если на уровне базового класса для универсального параметра установлено ограничение, то подобное ограничение должно 
            быть определено и в производных классах, которые также используют этот параметр:

                class BaseClass<T> where T : struct
                {
	                public T Field;
                }

                class DerivedClass<T> : BaseClass<T> where T : struct
                {
	                public T Property { get; set; }
