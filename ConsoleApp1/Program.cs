            Полиморфизм — это возможность объекта изменять и дорабатывать методы родительского объекта с целью решения прикладной задачи.

            Полиморфизм позволяет писать более абстрактные, расширяемые программы, один и тот же код используется для объектов разных классов, 
            улучшается читабельность кода. Полиморфизм позволяет избавить разработчика от написания, чтения и отладки множества if-else/switch-case конструкций.

            Для работы с полиморфизмом в C# нужно определить значение следующих понятий: виртуальный и абстрактный методы, переопределение метода.

                Виртуальный метод — это метод, который может быть переопределен в классе-наследнике.

            Такой метод обязан иметь стандартную реализацию в базовом классе. В C# виртуальные методы помечаются модификатором virtual.

                Переопределение метода — это изменение реализации виртуального метода в классе-наследнике.

            В C# переопределенные методы помечаются модификатором override. При обращении к экземпляру класса-наследника по его базовому типу (восходящее преобразование) 
            будет вызвана переопределенная реализация метода.

            Виртуальный и переопределенный методы должны иметь один и тот же модификатор доступа.

