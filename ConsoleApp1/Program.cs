            Перегрузка операторов
            --------------------------------------

            Помимо перегрузки методов существует еще и перегрузка операторов. Оператор по сути очень похож на метод с 1-2 параметрами. 
            При создании своих типов (классов и структур) бывает полезно использовать операторы, поскольку их использование будет выглядеть проще и понятнее.

            Рассмотрим пример с классом Vector для вектора с 2 координатами:

class Vector 
{
  public int X;
  public int Y;
}

            У вектора есть координаты X и Y. Для того чтобы сложить 2 вектора, нам нужно сложить величины координат X и координат Y 2 векторов.

            Для этого заведем 2 вектора a и b, а результатом должен будет стать вектор c:

Vector a = new Vector { X = 3, Y = 5 };
Vector b = new Vector { X = 7, Y = 13 };

            Для того чтобы получить значение координаты c.X, нужно сложить координаты a.X и b.X, аналогично для Y. Мы можем сделать это при инициализации:

Vector c = new Vector { X = a.X + b.X, Y = a.Y + b.Y };

            Но такой подход требует от нас знания того, как складываются вектора, к тому же при каждом сложении мы будем дублировать код. Можно написать метод в классе Vector

internal class Program
{
  static void Main(string[] args)
  {
    Vector a = new Vector { X = 3, Y = 5 };
    Vector b = new Vector { X = 7, Y = 13 };

    Vector c = a.Add(b);

    Console.WriteLine($"{c.X}, {c.Y}");
  }
}

class Vector
{
  public int X;
  public int Y;

  public Vector Add(Vector second)
  {
    return new Vector
    {
      X = this.X + second.X,
      Y = this.Y + second.Y
    };
  }
}

            И использовать его при каждом сложении вектора:

                Vector c = a.Add(b);

            Но нам придется следить за тем, чтобы метод был доступен во всей программе, и обязательно иметь экземпляр класса, чтобы вызывать данный метод.

            Чтобы избежать данных неудобств, а также получить более короткий способ сложить 2 экземпляра класса Vector, мы можем воспользоваться перегрузкой оператора +:

class Vector 
{
  //...
  public static Vector operator + (Vector a, Vector b) 
  {
    return new Vector 
    {
      X = a.X + b.X,
      Y = a.Y + b.Y
    };
  }
}

            Для объявления перегрузки оператора обязательно указывать модификаторы public и static, а после возвращаемого типа вместо метода указать ключевое 
            слово operator и уже следом сам оператор.

            После перегрузки оператора им можно будет воспользоваться в любой части программы, в которой будет виден класс, для которого выполняется перегрузка:

                 Vector c = a + b;

            Такое определение оператора по сути является методом, поэтому его тоже можно перегрузить, определив действие с тем же оператором, но для других операндов:

public static Vector operator + (Vector a) 
{
  return new Vector 
  {
    X = a.X,
    Y = a.Y
  };
}
public static Vector operator + (Vector a, (int X, int Y) b) {
  return new Vector 
  {
    X = a.X + b.X,
    Y = a.Y + b.Y
  };
}

            И можно будет использовать данные операторы следующим образом:

                Vector d = +a;
                Vector e = a + (10, -5);

            Важно запомнить, что при перегрузке не должны изменяться те объекты, которые передаются в оператор через параметры. Именно для этого 
            в примерах выше для возврата создается новый экземпляр класса Vector. Такой пример будет неправильным и приведет к путанице:

 public static Vector operator + (Vector a, Vector b) 
{
  a.X += b.X;
  a.Y += b.Y;

  return a;
}

            Ниже представлен список операторов, доступных к перегрузке:

                +x, -x, !x, ~x,                 Унарные операторы (операция над 1 элементом)
                ++, --, true, false


                x + y, x - y, x * y, x / y,     Бинарные операторы (операция над 2 элементами), которые перегружаются независимо друг от друга
                x % y, x & y, x | y, x ^ y,

                x << y, x >> y,


                x == y и x != y,                Бинарные операторы, которые перегружаются попарно (т.е. при перегрузке одного элемента из пары обязан быть перегружен и другой оператор)
                x < y и x > y,

                x <= y и x >= y

            Также важно отметить, что операторы +=, -=, *=, /=, %=, &=, |=, ^=, <<=, >>=  не могут быть перегружены, но используют перегрузки бинарных операторов, 
            с которыми связаны. Например, += будет использовать перегрузку оператора +.

