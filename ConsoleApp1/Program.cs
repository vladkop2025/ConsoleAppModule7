            --------------------------------------
            Ограничения обобщений
            --------------------------------------

            С помощью универсальных параметров мы можем типизировать обобщённые классы любым типом. Однако иногда возникает необходимость конкретизировать тип.

            Например, у нас есть следующий класс Order, который представляет заказ в интернет-магазине:

                class Order
                {
	                public int Number;

	                public string Description;

	                // ... Другие поля
                }

            Мы хотим добавить в заказ класс для организации доставки, но т.к. доставка может быть разных типов — мы сделаем тип Delivery базовым и унаследуем от него другие типы:

                HomeDelivery — доставка на дом. Этот тип будет подразумевать наличие курьера или передачу курьерской компании, в нём будет располагаться своя, 
                отдельная от прочих типов доставки, логика.

                PickPointDelivery — доставка в пункт выдачи. Здесь будет храниться какая-то ещё логика, необходимая для процесса доставки в пункт выдачи, например, хранение 
               компании и точки выдачи, а также какой-то ещё информации.

                ShopDelivery — доставка в розничный магазин. Эта доставка может выполняться внутренними средствами компании и совсем не требует работы с «внешними» элементами.

            Таким образом, мы получим следующую схему классов:

                abstract class Delivery
                {
	                public string Address;
                }

                class HomeDelivery : Delivery ... 
                class PickPointDelivery : Delivery ...
                class ShopDelivery : Delivery  ...

            Теперь мы можем добавить в класс следующий метод для работы с полем адреса:

                public void DisplayAddress()
                {
	                Console.WriteLine(Delivery.Address);
                }

            После внесенных изменений класс Order будет выглядеть следующим образом:

                class Order<T> where T : Delivery
                {
	                public int Number;

	                public string Description;

	                // ... Другие поля
                }

            А также мы не сможем создавать неверные типы из обобщения:

                Order<HomeDelivery> order1;	// Все работает
                Order<int> order2;		// Ошибка при компиляции

            Также в качестве ограничения может выступать и обобщённый класс:

                class PremiumService<T> where T : Order<HomeDelivery>
                {
	                public T Order;
                }

            Важно, что только один класс может использоваться в качестве ограничения универсального параметра.

            Стоит отметить, что компилятор не ограничивает нас в том, как называть универсальный параметр — T, U, V, Param или как-то ещё. Но в своих приложениях 
            бывает очень полезно по одному имени определять, что это универсальный параметр, и какие на него наложены ограничения.

            Например, нередко встречается такой подход, что универсальный параметр начинается с символа T, а далее он может описывать своё ограничение. Например, 
            для ограничения на класс Delivery мы можем назвать параметр TDelivery:


                class Order<TDelivery> where TDelivery : Delivery

            В качестве ограничений для параметра могут выступать:

                Определённый класс, используя его наименование.
                Определённый интерфейс, используя его наименование (об интерфейсах мы поговорим в одном из следующих модулей).
                Любой класс, используя ключевое слово class.
                Любая структура, используя ключевое слово struct.
                Любой тип с конструктором без параметров, используя new().
                Посмотрим на использование данных ограничений

            
                    -----------------------------------------------------------------------------
                    Ограничение	                                Пример
                    -----------------------------------------------------------------------------
                    Определённый класс	                        class Order<T> where T : Delivery
                    Любой класс	                                class Order<T> where T : class
                    Любая структура	                            class Order<T> where T : struct
                    Любой тип с конструктором без параметров	class Order<T> where T : new()

            Если класс использует несколько универсальных параметров, то последовательно можно задать ограничения к каждому из них:

                class Order<TDelivery, TStruct>
	            where TDelivery : Delivery
	            where TStruct : struct
                {
	                public TDelivery Delivery;

	                public TStruct Struct;

	                // ... Другие поля
                }

            Для методов синтаксис ограничений является точно таким же:

                Mpublic static T Return<T>(int number) where T : new()
                {
	                Console.WriteLine(number);

	                return new T();
                }

