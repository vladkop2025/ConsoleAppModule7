            7.5. Статические классы и элементы
            *************************

            Помимо обычных полей, свойств и методов, классы могут иметь их статические версии.

            Статический элемент класса (поле, свойство или метод) — такой элемент, который относится не к экземпляру, а к самому классу, и для работы с которым 
            не требуется создавать экземпляр класса.

            Для объявления статического элемента достаточно добавить модификатор static:

    class SimpleClass 
    {
      public static int MinValue = 100;

      public int Value;

      public SimpleClass(int value) 
      {
        if (value < MinValue) 
        {
          Value = MinValue;
        }
        else 
        {
          Value = value;
        }
      }
    }

            В данном примере класс SimpleClass имеет статическое поле — MinValue. Это поле может использоваться как в логике класса, просто 
            обращаясь к нему как к обычному полю, так и вне класа

                    SimpleClass object1 = new SimpleClass(50);
                    SimpleClass object2 = new SimpleClass(170);

            При проверке в конструкторе оба раза запрашивается значение MinValue, которое в памяти располагается вне экземпляров класса:

            При этом память для статических переменных выделяется даже в том случае, если не создано ни одного объекта этого класса. Но инициализация 
            поля произойдет только перед непосредственным обращением к статическому элементу, либо при создании экземпляра класса.

