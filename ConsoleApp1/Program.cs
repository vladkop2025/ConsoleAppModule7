            Представим, что у нас есть интернет-магазин и есть сущность — Заказ (Order). Изначально номер заказа был числовым, т.е. класс выглядел следующим образом:

class Order
{
	public int Number;

	public string Description;

	// ... Другие поля
}

            Но в один момент система начала расширяться, и потребовалось хранить ещё и строковые номера заказов (например, “NN-1234”). 
            Для того, чтобы не создавать новый класс с переносом логики и не выделять базовый, мы можем хранить данные в каком-то общем 
            родителе для типов int и string. Это, конечно же, object. Получим следующий класс:

class Order
{
	public object Number;

	public string Description;

	// ... Другие поля
}

            Таким образом, для работы с заказом мы сможем пользоваться различными типами номера заказа:

                Order order1 = new Order();
                Order order2= new Order();

                order1.Number = 1234;
                order2.Number = "NN-1234";

            И для того, чтобы воспользоваться значениями переменных для какой-то логики обработки, их нужно будет приводить к нужному типу, например, так:

                int number1 = (int)order1.Number;
                string number2 = (string)order2.Number;

            А чтобы не получить ошибку, если вдруг в заказе окажется не тот тип, который мы ожидали, нужно проверять типы, например, с использованием функции GetType():

if (order1.Number.GetType() == typeof(int))
{
	int number1 = (int)order1.Number;
}

if (order2.Number.GetType() == typeof(string))
{
	string number2 = (string)order2.Number;
}

            Данный подход плох по нескольким причинам:

                При использовании типа object для значимых типов происходит упаковка и распаковка, а, как мы знаем, её лучше избегать, поскольку это очень затратная операция.
                При преобразовании типов может произойти ошибка в работе программы из-за несоответствия типов.
                Для того, чтобы безопасно преобразовать объект в нужный тип, приходится писать различные проверки и конструкции, только усложняющие код.

            Поэтому в .Net 2.0 были представлены обобщения, которые решают эти проблемы. Благодаря обобщениям мы можем сделать класс Order универсальным — Order<T>:

                class Order<T>
                {
	                public T Number;

	                public string Description;

	                // ... Другие поля
                }

            Теперь поле Number будет того типа, который мы подставим в качестве параметра. Для этого при объявлении типа и при инициализации 
            переменной используем типы Order<int> и Order<string>:

                Order<int> order1 = new Order<int>();
                Order<string> order2 = new Order<string>();

                order1.Number = 1234;
                order2.Number = "NN-1234";

                int number1 = order1.Number;
                string number2 = order2.Number;

            Таким образом, используя обобщённый вариант класса, мы снижаем время на выполнение программы, количество потенциальных ошибок и упрощаем код.

